#!/usr/bin/env python3
"""Generate zero-delay Verilog simulation models from the functions in a Liberty file.
usage: gen_models.py <lib> <out.v>
Port names are exactly the Liberty pin names; power pins (pg_pin) are not modelled."""
import re, sys

lib, out = sys.argv[1], sys.argv[2]
txt = open(lib).read()

cells = {}
for m in re.finditer(r'^\s*cell\s*\(\s*(\w+)\s*\)\s*\{', txt, re.M):
    i, depth = m.end(), 1
    while depth:
        c = txt[i]
        depth += (c == '{') - (c == '}')
        i += 1
    cells[m.group(1)] = txt[m.end():i-1]

def vexpr(f):
    return f.replace('!', '~').replace('+', '|')

lines = ["// AUTO-GENERATED by gen_models.py from %s -- do not edit." % lib.split('/')[-1],
         "// Zero-delay functional models; port names = Liberty pin names.",
         "`timescale 1ns/1ps", ""]
for name, body in cells.items():
    pins = re.findall(r'pin\s*\(\s*(\w+)\s*\)\s*\{(.*?)\n\s{4}\}', body, re.S)
    ins  = [p for p, b in pins if 'direction : input' in b]
    outs = [(p, re.search(r'function\s*:\s*"([^"]+)"', b).group(1))
            for p, b in pins if 'direction : output' in b]
    latch = re.search(r'latch\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{(.*?)\}', body, re.S)
    ff    = re.search(r'\bff\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{(.*?)\}', body, re.S)
    ports = ", ".join(ins + [o for o, _ in outs])
    lines.append("module %s (%s);" % (name, ports))
    lines.append("  input %s;" % ", ".join(ins))
    lines.append("  output %s;" % ", ".join(o for o, _ in outs))
    if latch or ff:
        g = latch or ff
        iq, iqn, blk = g.group(1), g.group(2), g.group(3)
        lines.append("  reg %s;" % iq)
        if latch:
            en = re.search(r'enable\s*:\s*"([^"]+)"', blk).group(1)
            d  = re.search(r'data_in\s*:\s*"([^"]+)"', blk).group(1)
            lines.append("  always @* if (%s) %s = %s;" % (vexpr(en), iq, vexpr(d)))
        else:
            ck = re.search(r'clocked_on\s*:\s*"([^"]+)"', blk).group(1)
            ns = re.search(r'next_state\s*:\s*"([^"]+)"', blk).group(1)
            assert re.fullmatch(r'\w+', ck), "only plain rising-edge clocks supported: " + ck
            lines.append("  always @(posedge %s) %s <= %s;" % (ck, iq, vexpr(ns)))
        lines.append("  wire %s = ~%s;" % (iqn, iq))
    for o, f in outs:
        lines.append("  assign %s = %s;" % (o, vexpr(f)))
    lines.append("endmodule\n")
open(out, "w").write("\n".join(lines))
print("wrote %s (%d cells)" % (out, len(cells)))
